"""Assembles public/: exactly the files that belong on the live website (nomadceuticals.com), nothing else.

    python3 scripts/build_public.py

Upload the *contents* of public/ to the web host (Hostinger: public_html), or let
.github/workflows/deploy.yml publish it to the `public` branch for Hostinger's Git auto-deploy.
Source data, scripts, docs, images and research notes are never copied.
"""
import os
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "public")

HTACCESS = r"""# NomadCeuticals: web server rules (Hostinger / LiteSpeed / Apache). Generated by scripts/build_public.py.
Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On
  # One canonical address: https://nomadceuticals.com (no www, no http)
  RewriteCond %{HTTP_HOST} ^www\.nomadceuticals\.com$ [NC]
  RewriteRule ^(.*)$ https://nomadceuticals.com/$1 [R=301,L]
  RewriteCond %{HTTPS} !=on
  RewriteCond %{HTTP:X-Forwarded-Proto} !=https
  RewriteRule ^(.*)$ https://%{HTTP_HOST}/$1 [R=301,L]
</IfModule>

<IfModule mod_mime.c>
  AddType application/json .json
  AddType text/csv .csv
  AddType image/svg+xml .svg
  AddCharset utf-8 .json .csv .html .svg
</IfModule>

<IfModule mod_headers.c>
  Header always set X-Content-Type-Options "nosniff"
  # Public API and data files: any website may fetch them (CORS), cache for an hour
  <FilesMatch "\.(json|csv)$">
    Header always set Access-Control-Allow-Origin "*"
    Header always set Access-Control-Allow-Methods "GET, HEAD, OPTIONS"
    Header set Cache-Control "public, max-age=3600"
  </FilesMatch>
  <FilesMatch "\.(svg|webp|png|jpg)$">
    Header set Cache-Control "public, max-age=604800"
  </FilesMatch>
  <FilesMatch "\.html$">
    # no-cache = check with the server every time, so a new deploy shows up straight away
    Header set Cache-Control "no-cache"
  </FilesMatch>
</IfModule>

# Safety net: never serve source, tooling or research files even if they get uploaded by mistake
RedirectMatch 404 ^/(scripts|data|docs|research|i18n|images|\.github|\.git)(/|$)
RedirectMatch 404 ^/(README|CONTRIBUTING|CHANGELOG)\.md$
RedirectMatch 404 ^/(?!robots\.txt$).*\.(py|yml|yaml|txt|patch|zip|DS_Store)$
"""

NOT_FOUND = """<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>Not found · NomadCeuticals</title>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Source+Serif+4:opsz,wght@8..60,600;8..60,700&family=Source+Sans+3:wght@400;500&display=swap"><style>body{margin:0;font:18px/1.6 system-ui,sans-serif;background:#F3F5F7;color:#15202B}
main{max-width:640px;margin:15vh auto;padding:0 20px}h1{font-family:Georgia,serif;font-weight:600}a{color:#92171A}</style></head>
<body><!--__SITE_HEADER__--><main><h1>Page not found</h1><p>That address doesn't exist. Go to the <a href="/">NomadCeuticals home page</a> or the <a href="/api/">Medicines API docs</a>.</p></main></body></html>
"""


def main():
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    os.makedirs(os.path.join(OUT, "assets"))
    shutil.copy2(os.path.join(ROOT, "index.html"), OUT)
    shutil.copy2(os.path.join(ROOT, "otc-finder.html"), OUT)
    shutil.copy2(os.path.join(ROOT, "LICENSE.md"), OUT)
    for d in ("api", "dist", "schema"):
        shutil.copytree(os.path.join(ROOT, d), os.path.join(OUT, d), ignore=shutil.ignore_patterns(".DS_Store"))
    for f in sorted(os.listdir(os.path.join(ROOT, "assets"))):
        if f.startswith("logo") and f.endswith(".svg"):
            shutil.copy2(os.path.join(ROOT, "assets", f), os.path.join(OUT, "assets"))
    open(os.path.join(OUT, ".htaccess"), "w").write(HTACCESS)
    import site_header  # the shared top bar (scripts/site_header.*)
    open(os.path.join(OUT, "404.html"), "w", encoding="utf-8").write(site_header.inject(NOT_FOUND, base="/"))
    open(os.path.join(OUT, "robots.txt"), "w").write("User-agent: *\nAllow: /\n")
    n = sum(len(fs) for _, _, fs in os.walk(OUT))
    print(f"public/: {n} files ready to upload")


if __name__ == "__main__":
    main()
